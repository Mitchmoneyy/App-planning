// Renders the website's faith icons (src/lib/map/icons.ts) to PNGs for the phone app,
// at 1x/2x/3x, plus the list of images the app registers with the map.
//   node scripts/build-mobile-icons.cjs        (uses rolldown + Playwright's Chromium)
const { execFileSync } = require("child_process");
const fs = require("fs");
const os = require("os");
const path = require("path");
const { chromium } = require("playwright");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "mobile/assets/icons");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "gs-icons-"));
execFileSync(path.join(ROOT, "node_modules/.bin/rolldown"), ["src/lib/map/icons.ts", "--format", "esm", "--file", path.join(tmp, "icons.js")], { cwd: ROOT, stdio: "inherit" });
const code = fs.readFileSync(path.join(tmp, "icons.js"), "utf8");

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.route("**/*", (r) =>
    r.request().url().endsWith("/icons.js") ? r.fulfill({ body: code, contentType: "text/javascript" }) : r.fulfill({ body: "<!doctype html><body></body>", contentType: "text/html" }),
  );
  await page.goto("http://icons.local/");
  const images = await page.evaluate(async () => {
    const m = await import("/icons.js");
    const out = {};
    for (const ratio of [1, 2, 3]) {
      for (const { id, image } of m.allFaithIcons(ratio)) {
        const c = document.createElement("canvas");
        c.width = image.width;
        c.height = image.height;
        c.getContext("2d").putImageData(new ImageData(new Uint8ClampedArray(image.data), image.width, image.height), 0, 0);
        out[`${id}${ratio === 1 ? "" : `@${ratio}x`}.png`] = c.toDataURL().split(",")[1];
      }
    }
    return out;
  });
  await browser.close();
  fs.mkdirSync(OUT, { recursive: true });
  for (const [name, b64] of Object.entries(images)) fs.writeFileSync(path.join(OUT, name), Buffer.from(b64, "base64"));
  const names = [...new Set(Object.keys(images).map((n) => n.replace(/(@\dx)?\.png$/, "")))].sort();
  const list = [
    "/** Faith marker icons for the map (generated by scripts/build-mobile-icons.cjs; same drawings as the website). */",
    "/* eslint-disable @typescript-eslint/no-require-imports */",
    "export const FAITH_ICONS = {",
    ...names.map((n) => `  "${n}": require("../../assets/icons/${n}.png"),`),
    "};",
    "",
  ].join("\n");
  fs.writeFileSync(path.join(ROOT, "mobile/src/lib/faithIcons.ts"), list);
  console.log(`${Object.keys(images).length} icon files, ${names.length} icons`);
})();
